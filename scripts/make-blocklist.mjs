// Writes src/core/blocklist.js: every block of a Minecraft version with its
// properties and their default values. Minecraft keeps this list in its code,
// not in the game's files, so we take it from the open-source minecraft-data
// project (MIT licence, https://github.com/PrismarineJS/minecraft-data).
//
//   node scripts/make-blocklist.mjs 1.21.11
//
// Add a new game version by running it again with that version: the file
// keeps one list per version.
import { readFile, writeFile } from "node:fs/promises";

const version = process.argv[2] || "1.21.11";
const base = "https://raw.githubusercontent.com/PrismarineJS/minecraft-data/master/data/";
const paths = await (await fetch(base + "dataPaths.json")).json();
const dir = paths.pc[version]?.blocks;
if (!dir) throw new Error(`minecraft-data has no block list for ${version}`);
const blocks = await (await fetch(`${base}${dir}/blocks.json`)).json();
const shapes = await (await fetch(`${base}${paths.pc[version].blockCollisionShapes}/blockCollisionShapes.json`)).json();

/** What the editor draws a block as when it has no textures: by its name,
 * then by whether its default state fills the whole block. */
function shapeOf(b) {
  const n = b.name;
  if (n.endsWith("_stairs")) return "stairs";
  if (n.endsWith("_slab")) return "slab";
  if (n.endsWith("_pane") || n === "iron_bars") return "pane";
  if (n.endsWith("_carpet")) return "carpet";
  const s = shapes.blocks[n];
  const own = Array.isArray(s) ? s[b.defaultState - b.minStateId] : s;
  const box = shapes.shapes[own] || [];
  if (box.length === 1 && box[0].join() === "0,0,0,1,1,1") return "cube";
  if (!box.length) return "plant"; // nothing to bump into: flowers, grass, torches…
  return "other";
}

/** Blocks that are never placed: air and the piston's moving parts. */
const SKIP = new Set(["air", "cave_air", "void_air", "moving_piston"]);

/** Names used by more than one block (a torch and a wall torch are both
 * "Torch" in the game): those blocks are named after their id instead. */
const count = {};
for (const b of blocks) count[b.displayName] = (count[b.displayName] || 0) + 1;
const title = (id) => id.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");

const lines = [];
for (const b of blocks) {
  if (SKIP.has(b.name)) continue;
  // The default state's number, counted from the block's first state, gives
  // each property's default: the last property counts fastest.
  let n = b.defaultState - b.minStateId;
  const states = b.states || [];
  const props = new Array(states.length);
  for (let i = states.length - 1; i >= 0; i--) {
    const s = states[i];
    const values = s.type === "bool" ? ["true", "false"] : s.type === "int"
      ? (s.values || Array.from({ length: s.num_values }, (_, k) => String(k)))
      : s.values;
    const d = n % values.length;
    n = Math.floor(n / values.length);
    // Default value first.
    props[i] = s.name + ":" + [values[d], ...values.filter((_, k) => k !== d)].join(",");
  }
  const name = count[b.displayName] > 1 ? title(b.name) : b.displayName;
  lines.push(`${b.name}|${name}|${shapeOf(b)}${props.length ? "|" + props.join(";") : ""}`);
}

const file = new URL("../src/core/blocklist.js", import.meta.url);
let tables = {};
try {
  const old = await import(file.href);
  tables = { ...old.BLOCK_LISTS };
} catch (e) { /* first run */ }
tables[version] = lines.join("\n");
const out = `// Every block of each Minecraft version, with its properties. Generated by
// scripts/make-blocklist.mjs from minecraft-data (MIT licence,
// https://github.com/PrismarineJS/minecraft-data). Do not edit by hand.
//
// One line per block: "id|Name|shape|prop:default,other,…;prop:…" (the
// default value comes first). The shape is only for drawing without
// textures: cube (fills the whole block), stairs, slab, pane, carpet, plant
// (nothing to bump into) or other.

export const BLOCK_LISTS = {
${Object.entries(tables).map(([v, t]) => `  ${JSON.stringify(v)}: ${JSON.stringify(t)},`).join("\n")}
};
`;
await writeFile(file, out);
console.log(`${version}: ${lines.length} blocks`);
